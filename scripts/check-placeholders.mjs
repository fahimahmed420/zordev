// Lists every remaining placeholder and writes PLACEHOLDERS.md.
// Fails (exit 1) when STRICT: on Vercel production builds, or with `npm run check:launch`.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const strict = process.env.VERCEL_ENV === "production" || process.argv.includes("--strict");

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(ts|tsx|mdx)$/.test(name)) out.push(p);
  }
  return out;
}

const issues = [];
for (const file of walk(join(root, "content"))) {
  const lines = readFileSync(file, "utf8").split("\n");
  lines.forEach((line, i) => {
    const rel = relative(root, file).replaceAll("\\", "/");
    for (const m of line.matchAll(/ph\("([^"]+)"\)/g)) issues.push(`${rel}:${i + 1}: ${m[1]}`);
    for (const m of line.matchAll(/\[PLACEHOLDER: ([^\]]+)\]/g)) issues.push(`${rel}:${i + 1}: ${m[1]}`);
    if (/clientPermission:\s*"pending"/.test(line)) issues.push(`${rel}:${i + 1}: client permission still pending (case study)`);
  });
}

if (!process.env.NEXT_PUBLIC_BOOKING_URL) issues.push("env: NEXT_PUBLIC_BOOKING_URL (Cal.com link) not set");

const md = [
  "# Remaining placeholders",
  "",
  "Generated by `scripts/check-placeholders.mjs`. A production build fails until this list is empty.",
  "",
  ...(issues.length ? issues.map((i) => `- ${i}`) : ["None. Ready to launch."]),
  "",
].join("\n");
writeFileSync(join(root, "PLACEHOLDERS.md"), md);

console.log(`[placeholders] ${issues.length} remaining (see PLACEHOLDERS.md)`);
if (strict && issues.length) {
  console.error("[placeholders] Production build blocked: replace all placeholders first.");
  process.exit(1);
}
